function normalizeCityKey(value: string): string {
  return value.normalize('NFD').replace(/[\u0300-\u036f]/g, '').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
}

export function cityCentroid(
  countryCode?: string | null,
  country?: string | null,
  city?: string | null,
  stateProvince?: string | null
): CityCoordinate | null {
  if (!city) return null;
  const normalizedCity = normalizeCityKey(city);
  const normalizedState = stateProvince ? normalizeCityKey(stateProvince) : null;
  const code = countryCode ? countryCode.toUpperCase() : null;
  if (code && normalizedState) {
    const byState = CITY_CENTROIDS[`${code}:${normalizedState}:${normalizedCity}`];
    if (byState) return byState;
  }
  if (code) {
    const byEmptyState = CITY_CENTROIDS[`${code}::${normalizedCity}`];
    if (byEmptyState) return byEmptyState;

    const byCode = CITY_CENTROIDS[`${code}:${normalizedCity}`];
    if (byCode) return byCode;
  }
  if (country && normalizedState) {
    const byCountryState = CITY_CENTROIDS[`${normalizeCityKey(country)}:${normalizedState}:${normalizedCity}`];
    if (byCountryState) return byCountryState;
  }
  if (country) {
    const byCountryEmptyState = CITY_CENTROIDS[`${normalizeCityKey(country)}::${normalizedCity}`];
    if (byCountryEmptyState) return byCountryEmptyState;

    const byCountry = CITY_CENTROIDS[`${normalizeCityKey(country)}:${normalizedCity}`];
    if (byCountry) return byCountry;
  }
  return null;
}
